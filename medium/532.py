class Solution:
    def findPairs(self, nums: List[int], k: int) -> int:
        hm = {}
        ans = 0
        for num in nums:
            if num not in hm:
                hm[num] = 1
            else: 
                hm[num] += 1
        for num in hm:
            if k == 0:
                if hm[num] > 1:
                    ans += 1
            else:
                if (num + k) in hm:
                    ans += 1
        return ans


'''

Вначале преобразуем список чисел в мапу, где ключ - само число, 
а значение - колво повторений.

Потом прохожусь по мапе. Здесь обрабатываю два случая. 
Если k == 0, то по сути надо просто пары чисел одинаковых искать.
Если k != 0, тогда просто считаем, есть ли в мапе num + k (или num - k, это
не принципиально на самом деле). Условие гарантирует, что мы дважды не посчитаем
одну и ту же пару.

'''