from typing import List
class Solution:
    def moveZeroes(self, nums: List[int]) -> None:
        swap_index = 0
        for i in range(len(nums)):
            if nums[i] != 0:
                nums[i], nums[swap_index] = nums[swap_index], nums[i]
                swap_index += 1
        return nums

print(Solution().moveZeroes([1,0,2,3,5,0,9]))

'''

Здесь пускаем два указателя. Первый i - просто итерируется 
по всему массиву, а второй swap_index - служит границей, слева
от которой лежат только нужные числа. Сначала мы ищем первый ненулевой элемент
и помещаем его впереди, потом +1 к swap_index и вот мы уже потихоньку "сдвиагем"
границу на 1 вправо. Таким образом мы оставим все нули справа от границы.

Если у нас будет несколько нулей подряд, то мы просто пропустим их, ища ненулевые значения
после них, а если после них ничего не будет - значит, мы уже получили ответ

'''