class Solution:
    def isIsomorphic(self, s: str, t: str) -> bool:
        iso = {} 
        used = set() 
        for i in range(len(s)):

            if s[i] not in iso:
                if t[i] not in used:
                    iso[s[i]] = t[i]
                    used.add(t[i])
                else: 
                    return False

            elif t[i] != iso[s[i]]:
                return False
        return True


