def find_prefix(words):
    prefix = ""
    min_of_words = min([len(x) for x in words])
    for idx in range(min_of_words):
        compare_letter = words[0][idx] 
        for word in words:
            if word[idx] != compare_letter:
                return prefix
        prefix += compare_letter

    return prefix


